const fs=require('fs'),assert=require('assert');
const d=JSON.parse(fs.readFileSync(__dirname+'/../data.json','utf8'));
assert.strictEqual(d.version,'2.0.0');
assert.deepStrictEqual(d.days,Array.from({length:10},(_,i)=>`2026-09-${String(i+4).padStart(2,'0')}`));
assert.ok(d.works.length>=60,'works');
assert.ok(d.sessions.length>=120,'sessions');
const uniq=new Set(d.sessions.map(s=>`${s.date}|${s.start}|${s.place}|${s.workId}`)); assert.strictEqual(uniq.size,d.sessions.length,'duplicate sessions');
const g=d.works.find(w=>w.id==='gremlins-doc'),g2=d.works.find(w=>w.id==='gremlins-2');
assert.ok(g&&g2&&g.id!==g2.id); assert.ok(g.aliases.includes('American Nightmare'));
assert.strictEqual(d.sessions.filter(s=>s.workId==='gremlins-doc').length,3);
assert.strictEqual(d.sessions.filter(s=>s.workId==='gremlins-2').length,1);
assert.strictEqual(d.sessions.filter(s=>s.workId==='company').length,4);
const hotel=d.jury.find(x=>x.title==='Check-in hôtel'); assert.ok(hotel&&hotel.start==='15:00'&&hotel.end==='15:30');
const ret=d.jury.find(x=>x.title.includes('Trajet retour')); assert.ok(ret&&ret.date==='2026-09-13'&&ret.start==='12:12'&&ret.end==='14:29');
const queen=d.jury.find(x=>x.title.includes('Queen at Sea')); assert.ok(queen&&queen.start==='10:30'&&queen.end==='13:01');
const opening=d.jury.find(x=>x.title==='Cérémonie d’ouverture'); assert.ok(opening&&opening.start==='19:00'&&opening.end==='21:45');
const night=d.jury.find(x=>x.title==='Soirée d’ouverture'); assert.ok(night&&night.start==='23:30'&&night.end==='04:00');
assert.ok(d.events.some(x=>x.title==='Carte blanche « Mon cinéma américain » à Catherine Deneuve'&&x.date==='2026-09-12'&&x.start==='14:30'));
assert.ok(d.events.some(x=>x.title.includes('Patrick Schwarzenegger')&&x.date==='2026-09-11'&&x.start==='19:30'));
console.log(`V2.0.0 regression tests: OK (${d.works.length} works, ${d.sessions.length} sessions, ${d.jury.length} Jury items, ${d.events.length} public events)`);
